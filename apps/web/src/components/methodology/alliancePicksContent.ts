export type PickRound = "first" | "second";

/** The newest season key in `PICK_POSITION_COUNTS`: the table the next season is predicted with. */
export const PICK_TABLE_SEASON: number = Math.max(...Object.keys(PICK_POSITION_COUNTS).map(Number));

export const PICK_TABLE: PickPositionCounts = PICK_POSITION_COUNTS[PICK_TABLE_SEASON]!;

function sum(values: readonly number[]): number {
  return values.reduce((total, value) => total + value, 0);
}

/** Pick turns behind each round's counts. */
export const PICK_TABLE_TURNS: Readonly<Record<PickRound, number>> = {
  first: sum(PICK_TABLE.firstPick),
  second: sum(PICK_TABLE.secondPick),
};

export function pickCounts(round: PickRound): readonly number[] {
  return round === "first" ? PICK_TABLE.firstPick : PICK_TABLE.secondPick;
}

/**
 * The chance of each position, as fractions summing to 1, once the table is
 * cut to `teamsLeft` positions and rescaled: the same rule the simulation
 * applies at a pick turn. A table with no mass on the line puts the whole
 * chance on position 1, as the simulation takes the best team left then.
 */
export function pickChances(counts: readonly number[], teamsLeft: number): number[] {
  const line = Array.from({ length: teamsLeft }, (_, index) => counts[index] ?? 0);
  const total = sum(line);
  if (total <= 0) return line.map((_, index) => (index === 0 ? 1 : 0));
  return line.map((count) => count / total);
}

/** A chance as the page prints it: whole percent from 10%, one decimal below, "<0.1%" for a sliver, "0%" for none. */
export function formatChance(fraction: number): string {
  const percent = fraction * 100;
  if (percent === 0) return "0%";
  if (percent >= 9.95) return `${percent.toFixed(0)}%`;
  if (percent >= 0.05) return `${percent.toFixed(1)}%`;
  return "<0.1%";
}

/** 1st, 2nd, 3rd, 4th, ... 11th, 12th, 13th, 21st. */
export function ordinal(n: number): string {
  const suffixes = ["th", "st", "nd", "rd"];
  const lastTwo = n % 100;
  return `${n}${suffixes[(lastTwo - 20) % 10] ?? suffixes[lastTwo] ?? suffixes[0]}`;
}

