function formatPercent(value: number): string {
  return Number.isInteger(value) ? `${value}%` : `${value.toFixed(1)}%`;
}

/** "Weighted draft: said 4.5%, happened 6.6%, 2,005 teams", the point tooltip and the table row source. */
