/**
 * Writes `packages/core/districts/pickPositionTables.ts`, the weighted pick
 * draft's tables (quick task 261014-ol6), from the read only corpus.
 *
 * WHAT A TABLE IS: for each season Y the simulation can price, the count of
 * real district pick turns, from 2016 to Y - 1, whose real pick sat at each
 * position in the list of still available teams sorted by SPR. One list for
 * first picks and one for second picks. The counts are the SAME turns quick
 * task 261014-mji scored: `measurePickOrderHalf` over the `boundaryRatingsByEvent`
 * replay, so a team's SPR is the one it had after its last qualification match
 * at that event. The script refuses to write unless every season's counts
 * divide out to exactly `pickPositionTables`' own pmf.
 *
 * WALK FORWARD: season Y's table never holds a turn from Y or later. The last
 * season written is the one after the corpus's newest draft, the table live
 * predictions use.
 *
 *   npx tsx scripts/buildPickPositionTables.ts
 *
 * Read only corpus, no network, no environment variable.
 */
import { writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { openCorpusReadOnly } from "../packages/corpus/db.js";
import {
  boundaryRatingsByEvent,
  boundaryTotalsFromRatings,
  emptyCensus,
  measurePickOrderHalf,
  type TurnResult,
} from "./measureSelectionAgreement.js";
import { FIRST_SCORABLE_SEASON, pickPositionTables } from "./measureRandomPickDraft.js";
import { parseSeasons } from "./scriptHelpers.js";

const CORPUS_PATH = "data/corpus.sqlite";
const OUTPUT_PATH = "packages/core/districts/pickPositionTables.ts";
/** The first season whose drafts enter a table, the same window 261014-mji's primary tables used. */
export const TRAIN_FROM = 2016;

/** Count of turns at each position 1 to the deepest seen, for one round of the seasons `[trainFrom, season)`. */
export function positionCounts(turns: readonly TurnResult[], season: number, trainFrom: number, round: 1 | 2): number[] {
  const kept = turns.filter((turn) => turn.round === round && turn.season >= trainFrom && turn.season < season);
  let deepest = 0;
  for (const turn of kept) if (turn.modelRank > deepest) deepest = turn.modelRank;
  const counts = new Array<number>(deepest).fill(0);
  for (const turn of kept) counts[turn.modelRank - 1]! += 1;
  return counts;
}

function main(): void {
  const db = openCorpusReadOnly(CORPUS_PATH);
  const newest = (db.prepare("SELECT MAX(year) AS y FROM event_alliances JOIN events USING (event_key)").get() as { y: number }).y;
  const replay = parseSeasons(`${String(TRAIN_FROM)}-${String(newest)}`);
  process.stderr.write(`replaying SPR ${String(TRAIN_FROM)} to ${String(newest)} ...\n`);
  const ratings = boundaryRatingsByEvent(db, replay, TRAIN_FROM);
  const pick = measurePickOrderHalf(db, replay, TRAIN_FROM, emptyCensus(), boundaryTotalsFromRatings(ratings));
  process.stderr.write(`${String(pick.turns.length)} pick turns over ${String(pick.eventsScored)} events\n`);

  const seasons: number[] = [];
  for (let season = FIRST_SCORABLE_SEASON; season <= newest + 1; season++) seasons.push(season);

  const blocks: string[] = [];
  for (const season of seasons) {
    const first = positionCounts(pick.turns, season, TRAIN_FROM, 1);
    const second = positionCounts(pick.turns, season, TRAIN_FROM, 2);
    // The refusal: these counts must BE the measured pmf, to the last bit.
    const measured = pickPositionTables(pick.turns, season, TRAIN_FROM);
    const sum = (a: readonly number[]) => a.reduce((x, y) => x + y, 0);
    const same = (counts: readonly number[], pmf: readonly number[]) =>
      counts.length === pmf.length && counts.every((c, i) => c / sum(counts) === pmf[i]);
    if (!same(first, measured.pmf.firstPick) || !same(second, measured.pmf.secondPick)) {
      throw new Error(`season ${String(season)}: counts do not reproduce pickPositionTables' pmf`);
    }
    blocks.push(
      `  ${String(season)}: {\n    seasonsFrom: ${String(TRAIN_FROM)},\n    seasonsTo: ${String(season - 1)},\n` +
        `    firstPick: [${first.join(", ")}],\n    secondPick: [${second.join(", ")}],\n  },`
    );
    process.stderr.write(
      `${String(season)}: first ${String(sum(first))} turns (position 1 ${((100 * first[0]!) / sum(first)).toFixed(1)}%), ` +
        `second ${String(sum(second))} turns (position 1 ${((100 * second[0]!) / sum(second)).toFixed(1)}%)\n`
    );
  }

  const source = `/**
 * THE WEIGHTED PICK DRAFT'S TABLES. GENERATED by \`scripts/buildPickPositionTables.ts\`
 * from the read only corpus; do not edit by hand, rerun the script.
 *
 * For each season the simulation prices, the number of real district pick
 * turns whose real pick sat at each position in the list of still available
 * teams sorted by SPR (position 1 = the best team left), counted from
 * \`seasonsFrom\` to \`seasonsTo\`. Walk forward: a season's table never holds a
 * turn from that season or later. The counts are the turns quick task
 * 261014-mji measured, and the generator refuses to write unless they divide
 * out to that measurement's pmf exactly.
 */

/** One season's counts: index 0 is position 1. */
export interface PickPositionCounts {
  readonly seasonsFrom: number;
  readonly seasonsTo: number;
  readonly firstPick: readonly number[];
  readonly secondPick: readonly number[];
}

export const PICK_POSITION_COUNTS: Readonly<Record<number, PickPositionCounts>> = {
${blocks.join("\n")}
};
`;
  writeFileSync(OUTPUT_PATH, source, "utf8");
  process.stderr.write(`wrote ${OUTPUT_PATH}\n`);
}

const isEntryPoint = process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isEntryPoint) main();
